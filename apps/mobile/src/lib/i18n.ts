export type Lang = 'fr' | 'en';
export type TextKey = { [K in keyof Dict]: Dict[K] extends string ? K : never }[keyof Dict];
export const dictionaries: Record<Lang, Dict> = { fr, en };

export const dayNames = (lang: Lang): string[] => dictionaries[lang].days;

export function translate(lang: Lang, key: TextKey): string {
  return dictionaries[lang][key] ?? dictionaries.fr[key];
}

// Turns a server error code (e.g. SLOT_TAKEN) into a sentence.
export function errorText(lang: Lang, code: string | undefined): string {
  const key = `err_${code}` as TextKey;
  return key in dictionaries[lang] ? translate(lang, key) : translate(lang, 'err_generic');
}
